const assert=require("node:assert/strict");
const path=require("node:path");

module.exports=async function checkStoryFlow(browser,base){
  const page=await browser.newPage({viewport:{width:1050,height:800}});
  const errors=[];
  page.on("pageerror",error=>errors.push(error.message));
  page.setDefaultTimeout(12000);
  const button=name=>page.getByRole("button",{name,exact:true});
  const label=name=>page.getByLabel(name,{exact:true});
  const saved=()=>page.getByText("이 브라우저에 저장했습니다.",{exact:true}).waitFor();
  try{
    await page.goto(new URL("editor/",base).href);
    await button("＋ 콘텐츠 추가").click();
    await page.locator("#add-kind").selectOption("expression");
    await label("표정을 사용할 인물").selectOption("soma");
    await label("표정 이름").fill("검증 표정");
    await page.locator("#add-file").setInputFiles(path.resolve(__dirname,"../../current/assets/portraits/soma.webp"));
    await button("추가하고 저장").click();
    await page.getByRole("heading",{name:"소마 · 검증 표정"}).waitFor();
    await button("이벤트").click();
    await button("＋ 이벤트").click();
    await page.locator("#new-title").fill("편지의 도착");
    await page.locator("#new-result").fill("봉투를 보관했다.");
    await label("1번 대사").fill("편지가 도착했다.");
    await button("브라우저에 저장").click();
    await saved();
    await button("장면 흐름도").click();
    await button("＋ 선택지 추가").click();
    await label("버튼 문구").fill("봉인을 살핀다");
    await label("선택 후 대사").fill("봉인이 열렸다.");
    await label("선택 조건").selectOption("통찰");
    await label("필요 수치 이상").fill("500");
    await button("새 장면을 만들어 연결").click();
    await page.locator("#new-title").fill("봉투 속 쪽지");
    await page.locator("#new-result").fill("기록했다.");
    await label("1번 대사").fill("접힌 쪽지가 보인다.");
    await page.getByText("1번 대사 연출",{exact:true}).click();
    await label("왼쪽 스탠딩").selectOption("soma");
    await label("왼쪽 표정").selectOption({label:"검증 표정"});
    await button("브라우저에 저장").click();
    await page.getByRole("heading",{name:"봉투 속 쪽지",exact:true}).waitFor();
    await page.reload();
    const search=page.getByRole("searchbox");
    await search.fill("편지의 도착");
    await page.locator("#list button").filter({hasText:"편지의 도착"}).click();
    await button("장면 흐름도").click();
    const map=page.locator(".connection-map");
    await map.getByRole("button",{name:"봉투 속 쪽지",exact:true}).waitFor();
    await map.locator("svg path").first().waitFor({state:"attached"});
    assert.equal(await map.locator("svg path").count(),1);
    await button("게임에서 미리보기 ↗").click();
    const game=page.frameLocator("#game-dialog iframe");
    const locked=game.getByRole("button",{name:/봉인을 살핀다.*500/});
    await locked.waitFor();
    assert.equal(await locked.isEnabled(),false);
    await button("닫기").click();
    await map.getByRole("button",{name:"봉인을 살핀다 · 봉투 속 쪽지 연결 편집"}).click();
    await label("필요 수치 이상").fill("0");
    await button("게임에서 미리보기 ↗").click();
    await game.getByRole("button",{name:"봉인을 살핀다",exact:true}).click();
    await game.getByText("봉인이 열렸다.",{exact:true}).waitFor();
    await game.getByRole("button",{name:"다음 장면",exact:true}).click();
    await game.getByText("접힌 쪽지가 보인다.",{exact:true}).waitFor();
    const image=game.locator("#conversation .cast-left img");
    assert.match(await image.getAttribute("src"),/assets\/expressions\/extra-/);
    await image.evaluate(element=>element.decode());
    await game.getByRole("button",{name:"기록을 덮는다",exact:true}).click();
    await game.getByText("기록했다.",{exact:true}).waitFor();
    await button("닫기").click();
    await button("장면 흐름도").click();
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    assert.deepEqual(errors,[]);
    console.log("PASS editor story graph, condition lock, linked scene, saved expression and mobile width");
  }finally{await page.close();}
};
