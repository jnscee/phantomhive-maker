"use strict";

function canReceiveSnake(run){
  return run.duration===35 && Boolean(run.flags.townhouse && run.people.soma && run.flags.agni)
    && !run.people.snake && !run.flags.snakeArrival;
}

function queueSnakeArrival(run,firstMonth=run.month){
  if(!canReceiveSnake(run))return;
  if(run.snakeArrivalMonth==null){
    const first=Math.min(firstMonth,run.duration);
    const window=Math.min(3,run.duration-first+1);
    run.snakeArrivalMonth=first+Math.floor(Math.random()*window);
  }
  if(run.month<run.snakeArrivalMonth||run.pending==="snakeArrival")return;
  run.eventQueue??=[];
  if(!run.eventQueue.includes("snakeArrival"))run.eventQueue.push("snakeArrival");
}

